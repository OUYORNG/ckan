const { chromium } = require('../../node_modules/playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const output = path.resolve(__dirname, '../test-results');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://localhost:5100/dataset', { waitUntil: 'networkidle' });
    const sidebar = page.locator('#portal-sidebar');
    const main = page.locator('.main-shell');
    const navigation = page.getByRole('navigation', { name: 'Main navigation' });
    assert.equal((await page.locator('.topbar').boundingBox()).height, 64);
    assert.equal((await sidebar.boundingBox()).width, 232);
    await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click();
    await page.getByRole('button', { name: 'Expand sidebar', exact: true }).waitFor();
    assert.equal((await sidebar.boundingBox()).width, 76);
    assert.equal(await main.evaluate(element => getComputedStyle(element).marginLeft), '76px');
    assert.equal(await page.locator('.brand-text').isVisible(), false);
    assert.equal(await navigation.locator('.nav-label').first().isVisible(), false);
    assert.equal(await navigation.getByRole('link', { name: 'Data catalog', exact: true }).getAttribute('title'), 'Data catalog');
    await page.screenshot({ path: path.join(output, 'sidebar-collapsed.png'), fullPage: true });
    await sidebar.hover();
    assert.equal((await sidebar.boundingBox()).width, 232);
    assert.equal(await page.locator('.brand-text').isVisible(), true);
    assert.equal(await navigation.locator('.nav-label').first().isVisible(), true);
    assert.equal(await main.evaluate(element => getComputedStyle(element).marginLeft), '76px', 'Hover expansion must overlay the page without shifting it.');
    assert.equal(await page.evaluate(() => localStorage.getItem('nis-sidebar-collapsed')), 'true');
    await page.screenshot({ path: path.join(output, 'sidebar-hover-expanded.png'), fullPage: true });
    await navigation.getByRole('link', { name: 'Organizations', exact: true }).click();
    await page.waitForURL('**/organization');
    await page.mouse.move(500, 100);
    assert.equal((await sidebar.boundingBox()).width, 76);
    await page.reload({ waitUntil: 'networkidle' });
    assert.equal((await sidebar.boundingBox()).width, 76);
    assert.equal(await page.evaluate(() => localStorage.getItem('nis-sidebar-collapsed')), 'true');
    await sidebar.hover();
    await page.getByRole('link', { name: 'View API guide', exact: true }).click();
    await page.waitForURL('**/api-guide');
    await page.mouse.move(500, 100);
    await navigation.getByRole('link', { name: 'Overview', exact: true }).focus();
    await page.keyboard.press('Tab');
    assert.equal((await sidebar.boundingBox()).width, 232);
    await page.getByRole('button', { name: 'Expand sidebar', exact: true }).focus();
    assert.equal((await sidebar.boundingBox()).width, 76);
    await page.setViewportSize({ width: 1024, height: 900 });
    assert.equal((await sidebar.boundingBox()).width, 76);
    const expand = page.getByRole('button', { name: 'Expand sidebar', exact: true });
    await expand.focus(); await page.keyboard.press('Enter');
    await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).waitFor();
    assert.equal((await sidebar.boundingBox()).width, 210);
    assert.equal(await page.locator('.brand-text').isVisible(), true);
    await page.reload({ waitUntil: 'networkidle' });
    assert.equal(await page.evaluate(() => localStorage.getItem('nis-sidebar-collapsed')), 'false');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: path.join(output, 'sidebar-expanded.png'), fullPage: true });
    await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await main.evaluate(element => getComputedStyle(element).marginLeft), '0px');
    assert.equal((await page.locator('.topbar').boundingBox()).height, 56);
    assert.equal(await page.getByRole('button', { name: 'Expand sidebar', exact: true }).isVisible(), false);
    const menu = page.getByRole('button', { name: 'Open navigation', exact: true });
    await menu.click();
    assert.equal(await menu.getAttribute('aria-expanded'), 'true');
    assert.equal((await sidebar.boundingBox()).width, 232);
    assert.equal(await page.locator('.brand-text').isVisible(), true);
    assert.equal(await navigation.locator('.nav-label').first().isVisible(), true);
    await page.screenshot({ path: path.join(output, 'sidebar-mobile.png'), fullPage: true, animations: 'disabled' });
    await page.keyboard.press('Escape');
    assert.equal(await menu.getAttribute('aria-expanded'), 'false');
    await menu.click();
    await navigation.getByRole('link', { name: 'Data catalog', exact: true }).click();
    await page.waitForURL('**/dataset');
    assert.equal(await menu.getAttribute('aria-expanded'), 'false');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: 'Expand sidebar', exact: true }).waitFor();
    await page.mouse.move(500, 100);
    assert.equal((await sidebar.boundingBox()).width, 76);
    assert.deepEqual(errors, []);
    console.log('Sidebar collapse/expand, temporary hover/focus expansion, navigation, persisted preference, mobile drawer, and compact header passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
